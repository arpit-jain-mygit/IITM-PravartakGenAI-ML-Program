def src(obj, max_lines=40):
    s = textwrap.dedent(inspect.getsource(obj)).rstrip().split("\n")
    return "\n".join(s[:max_lines] + (["    ..."] if len(s) > max_lines else []))


f2, f3 = lambda v: f"{v:.2f}", lambda v: f"{v:.3f}"

