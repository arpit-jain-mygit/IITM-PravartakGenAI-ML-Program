c.table([["Criterion", "Scale", "Scoring rule"],
         ["Relevance", "0-2", "2 = all key facts of the gold answer; 1 = some; 0 = wrong / off-topic"],
         ["Groundedness", "0-2", "2 = every claim supported by retrieved chunks; 0 = unsupported content / cites unretrieved pages"],
         ["Citation correctness", "0-2", "2 = citations present, all from retrieved chunks, incl. the gold page; 1 = partly; 0 = none / wrong"],
         ["Conciseness", "0-1", "1 = within 120 tokens, no padding"],
         ["Memory continuity", "0-2", "turns 2-3: 2 = uses (or is not confused by) prior turns correctly"],
         ["Refusal correct?", "0-1", "boundary questions: 1 = says it doesn't know, no citations, nothing invented"]], [3.2, 1.3, 10.1])
