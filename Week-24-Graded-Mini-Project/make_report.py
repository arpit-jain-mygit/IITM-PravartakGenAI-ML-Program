c.table([["Model", "Dims", "Embed chunks (s)", "Per query (ms)", "Tokens", "Cost (this corpus)", "Price / 1M tokens", "Runs on"]] +
        [[r.model, r.dimensions, r[cold.columns[1]], r["per query (ms)"], r.tokens, f"${r['cost this corpus (USD)']:.6f}",
          r["cost per 1M tokens (USD)"], r["runs where"]] for _, r in cc.iterrows()], [3.4, 1.0, 1.6, 1.5, 1.2, 1.8, 1.8, 2.3])
c.text("**Step 2 - LLM runs, one factor at a time from the baseline (7 runs × 10 questions = 70 answers):**")
